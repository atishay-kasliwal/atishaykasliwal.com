import path from "node:path";
import { pathToFileURL } from "node:url";
import { defineConfig } from "vite";
import fs from "node:fs";
import { buildCaseStudies } from "./scripts/build-case-studies.mjs";
import { buildPhotography } from "./scripts/build-photography.mjs";
import { renderPhotographySeo } from "./scripts/photography-seo.mjs";
import { buildExperiencePages } from "./scripts/build-experience-pages.mjs";
import { buildProfilePage } from "./scripts/build-profile-page.mjs";

// Google Analytics 4. Runs only on the production host, so local development, Lighthouse CI and
// Pages preview deployments are not counted, and loads gtag.js once the page is idle so it stays
// off the critical rendering path.
const GA_MEASUREMENT_ID = "G-RX5HTCRR3X";
const analyticsSnippet = `(function (w, d) {
  if (!/^(www\\.)?atishaykasliwal\\.com$/.test(location.hostname)) return;
  w.dataLayer = w.dataLayer || [];
  w.gtag = function () { w.dataLayer.push(arguments); };
  w.gtag("js", new Date());
  w.gtag("config", "${GA_MEASUREMENT_ID}");
  function load() {
    var script = d.createElement("script");
    script.async = true;
    script.src = "https://www.googletagmanager.com/gtag/js?id=${GA_MEASUREMENT_ID}";
    d.head.appendChild(script);
  }
  w.addEventListener("load", function () {
    if ("requestIdleCallback" in w) w.requestIdleCallback(load, { timeout: 3000 });
    else setTimeout(load, 1500);
  }, { once: true });
})(window, document);`;

// Appends the experience/education and profile pages' <url> entries to the sitemap that
// buildCaseStudies() already wrote, rather than each script owning its own file.
function mergeSitemapEntries(entries) {
  const file = path.resolve("public/sitemap.xml");
  const xml = fs.readFileSync(file, "utf8");
  if (!xml.includes("</urlset>")) return;
  fs.writeFileSync(file, `${xml.replace("</urlset>", `${entries}\n</urlset>`).trimEnd()}\n`);
}

// Each indexable document has its own emitted HTML file.
export default defineConfig(async () => {
  const pages = await buildCaseStudies();
  const photography = await buildPhotography();
  const experience = await buildExperiencePages();
  const profile = await buildProfilePage();
  mergeSitemapEntries(`${experience.sitemap}\n${profile.sitemap}`);
  return {
    build: {
      rollupOptions: {
        input: {
          main: path.resolve("index.html"),
          ...pages,
          ...photography,
          ...experience.inputs,
          ...profile.inputs,
          "photography/admin/index": path.resolve("src/photography-admin/index.html"),
          "admin/resume/index": path.resolve("src/admin/resume/index.html"),
          "admin/responses/index": path.resolve("src/admin/responses/index.html"),
        },
      },
    },
    plugins: [
      {
        // Every public page gets the analytics tag; the private admin pages do not.
        name: "google-analytics",
        apply: "build",
        transformIndexHtml(html, ctx) {
          if (ctx.filename.includes(`${path.sep}photography-admin${path.sep}`)) return html;
          if (ctx.filename.includes(`${path.sep}src${path.sep}admin${path.sep}`)) return html;
          return [{ tag: "script", children: analyticsSnippet, injectTo: "head" }];
        },
      },
      {
        // Private admin pages never ship as static files: Pages matches Functions on the raw URL
        // but serves assets from the decoded one, so a static copy could be fetched as
        // /%61dmin/resume/ without passing functions/admin/_middleware.js. Their built HTML goes
        // into a generated module that functions/admin/[[path]].js serves after the Access check.
        name: "admin-routes",
        closeBundle() {
          const pages = {};
          const photography = path.resolve("dist/src/photography-admin/index.html");
          if (fs.existsSync(photography)) pages.photography = fs.readFileSync(photography, "utf8");
          for (const name of ["resume", "responses"]) {
            const file = path.resolve(`dist/src/admin/${name}/index.html`);
            if (fs.existsSync(file)) pages[name] = fs.readFileSync(file, "utf8");
          }
          if (Object.keys(pages).length) {
            const out = path.resolve("functions/_generated/admin-pages.js");
            fs.mkdirSync(path.dirname(out), { recursive: true });
            fs.writeFileSync(out, `// Generated by vite.config.js (admin-routes) on every build. Do not edit or commit.\nexport default ${JSON.stringify(pages, null, 2)};\n`);
          }
          fs.rmSync(path.resolve("dist/src"), { recursive: true, force: true });
          fs.rmSync(path.resolve("dist/admin"), { recursive: true, force: true });
          fs.rmSync(path.resolve("dist/photography/admin"), { recursive: true, force: true });
        },
      },
      {
        name: "photography-seo",
        transformIndexHtml: {
          order: "pre",
          async handler(html) {
            if (!html.includes("<!-- photography:metadata -->")) return html;
            const data = pathToFileURL(path.resolve("src/photography.js")).href;
            const { photographs, photographyPage } = await import(`${data}?t=${Date.now()}`);
            return renderPhotographySeo(html, photographs, photographyPage);
          },
        },
      },
      {
        // GitHub status lines from the committed snapshot, so the build never calls GitHub.
        name: "github-activity",
        transformIndexHtml: {
          order: "pre",
          async handler(html) {
            if (!html.includes("<!-- github:column -->")) return html;
            const stamp = Date.now();
            const { renderGithubColumn, renderGithubFact } = await import(
              `${pathToFileURL(path.resolve("src/github-activity.js")).href}?t=${stamp}`
            );
            const activity = JSON.parse(fs.readFileSync(path.resolve("src/github-activity.json"), "utf8"));
            return html
              .replace("<!-- github:column -->", renderGithubColumn(activity))
              .replace("<!-- github:fact -->", renderGithubFact(activity));
          },
        },
      },
      {
        // The homepage Person is generated from the canonical profile (src/profile/build.js), the
        // same source as /profile and /api/profile.json, so the three never disagree. The page's
        // dateModified comes from src/case-studies/data.js like every other page date.
        name: "canonical-person",
        transformIndexHtml: {
          order: "pre",
          async handler(html, ctx) {
            if (path.resolve(ctx.filename) !== path.resolve("index.html")) return html;
            const pattern = /(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/;
            const match = html.match(pattern);
            if (!match || !match[2].includes('"Person"')) return html;
            const stamp = Date.now();
            const load = file => import(`${pathToFileURL(path.resolve(file)).href}?t=${stamp}`);
            const [{ buildProfile, personJsonLd }, { staticPageLastModified }] = await Promise.all([
              load("src/profile/build.js"),
              load("src/case-studies/data.js"),
            ]);
            const data = JSON.parse(match[2]);
            const profile = buildProfile();
            data["@graph"] = data["@graph"].map(node => {
              if (node["@type"] === "Person") return personJsonLd(profile, { mainEntityOfPage: "https://atishaykasliwal.com/#profile" });
              if (node["@type"] === "ProfilePage") return { ...node, dateModified: staticPageLastModified.homepage };
              return node;
            });
            const json = JSON.stringify(data, null, 2).replace(/\n/g, "\n      ");
            return html.replace(pattern, `$1\n      ${json}\n    $3`);
          },
        },
      },
      {
        // Prerender the work, experience and open source carousels so their cards, and the links
        // to every project and experience page, are in the homepage HTML before JavaScript.
        name: "prerender-carousels",
        transformIndexHtml: {
          order: "pre",
          async handler(html) {
            const stamp = Date.now();
            const load = file => import(`${pathToFileURL(path.resolve(file)).href}?t=${stamp}`);
            const [{ renderCarouselTrack }, { projects }, { experience }, { openSource }, { volunteer, events }] = await Promise.all([
              load("src/carousel-cards.js"),
              load("src/projects.js"),
              load("src/experience.js"),
              load("src/open-source.js"),
              load("src/volunteer.js"),
            ]);
            const fill = (source, id, items, options) => {
              const empty = `<div class="carousel-track" id="${id}"></div>`;
              return source.replace(
                empty,
                `<div class="carousel-track" id="${id}" data-prerendered="true">${renderCarouselTrack(items, options)}</div>`,
              );
            };
            // The caption and total each carousel shows before JavaScript runs, in the same format
            // src/project-carousel.js gives them, so raw HTML never shows a stale count or caption.
            const escapeText = value => String(value).replace(/[&<>]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" })[c]);
            const label = (source, prefix, items) =>
              source
                .replace(
                  new RegExp(`(<p id="${prefix}selected-project" data-carousel-caption>)[\\s\\S]*?(</p>)`),
                  `$1${escapeText(items[0].name)} <span>— ${escapeText(items[0].category)}</span>$2`,
                )
                .replace(
                  new RegExp(`(id="${prefix}total-count" data-carousel-total>)\\d+(<)`),
                  `$1${String(items.length).padStart(2, "0")}$2`,
                );
            // Same order as src/main.js gives the open source carousel.
            const community = [...openSource, ...volunteer, ...events];
            let output = fill(html, "carousel-track", projects, { eagerFirst: true });
            output = fill(output, "experience-carousel-track", experience);
            output = fill(output, "open-source-carousel-track", community);
            output = label(output, "", projects);
            output = label(output, "experience-", experience);
            return label(output, "open-source-", community);
          },
        },
      },
      {
        name: "case-studies",
        // Rebuild the pages when their data changes during development.
        configureServer(server) {
          const data = [
            path.resolve("src/case-studies/data.js"),
            path.resolve("src/photography.js"),
            path.resolve("src/experience-pages.js"),
            path.resolve("src/carousel-cards.js"),
            path.resolve("src/projects.js"),
            path.resolve("src/experience.js"),
            path.resolve("index.html"),
            path.resolve("src/github-activity.json"),
            path.resolve("src/open-source.js"),
            path.resolve("src/volunteer.js"),
            path.resolve("src/profile/data.js"),
            path.resolve("src/profile/build.js"),
            path.resolve("src/profile/open-source-contributions.json"),
          ];
          server.watcher.add(data);
          server.watcher.on("change", async file => {
            if (!data.includes(file)) return;
            await buildCaseStudies();
            await buildPhotography();
            const experience = await buildExperiencePages();
            const profile = await buildProfilePage();
            mergeSitemapEntries(`${experience.sitemap}\n${profile.sitemap}`);
            server.ws.send({ type: "full-reload" });
          });
        },
      },
    ],
  };
});
