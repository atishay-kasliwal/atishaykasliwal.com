// Checks the résumé PDF bundled with this build against this build's canonical profile, once, and
// emits the result as a private Functions module. The admin dashboard reads it instead of parsing
// the PDF on every request, which would exceed the Workers Free plan's CPU limit.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { checkResume } from "../src/resume-core/report.js";
import { RESUME_PATH, versionIdOf } from "../src/resume-core/constants.js";
import { reviewItems } from "../src/profile/review.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");
const bytes = new Uint8Array(fs.readFileSync(path.join(dist, RESUME_PATH)));
const profile = JSON.parse(fs.readFileSync(path.join(dist, "api", "profile.json"), "utf8"));
const report = await checkResume(bytes, { filename: path.basename(RESUME_PATH), contentType: "application/pdf", profile, reviewItems });
if (!report.ok) throw new Error(`The bundled résumé fails validation: ${report.validation.errors.join(" ")}`);

const bundled = {
  id: versionIdOf(report.sha256),
  sha256: report.sha256,
  sizeBytes: bytes.length,
  report: { consistency: report.consistency, checkedAt: report.checkedAt },
};
const outDir = path.join(root, "functions", "_generated");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "bundled-resume.js"), `// Generated by scripts/build-resume-report.mjs. Do not edit or commit.\nexport default ${JSON.stringify(bundled)};\n`);
const { conflict, unverified } = report.consistency.summary;
console.log(`Bundled résumé ${bundled.id}: ${conflict} conflicts, ${unverified} unverified against the profile.`);
