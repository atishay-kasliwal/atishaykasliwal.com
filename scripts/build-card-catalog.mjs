// Lists every carousel card (id, section, name, built-in image) as a private Functions module, so
// the thumbnail admin API and the homepage Function know which cards exist without importing the
// card modules at runtime. See docs/card-thumbnails.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { catalogOf } from "../src/card-thumbnails.js";
import { projects } from "../src/projects.js";
import { openSource } from "../src/open-source.js";
import { volunteer, events } from "../src/volunteer.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cards = [...catalogOf("project", projects), ...catalogOf("open-source", openSource), ...catalogOf("volunteer", [...volunteer, ...events])];
const ids = new Set(cards.map(card => card.id));
if (ids.size !== cards.length) throw new Error("Two carousel cards share an id; give one of them a different name or slug.");

const outDir = path.join(root, "functions", "_generated");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "card-catalog.js"), `// Generated by scripts/build-card-catalog.mjs. Do not edit or commit.\nexport default ${JSON.stringify(cards)};\n`);
console.log(`Card catalog: ${cards.length} cards.`);
